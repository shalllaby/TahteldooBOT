#!/bin/bash
# ==============================================================================
# سكربت التحديث السريع لمنظومة جريدة تحت الضوء من GitHub
# الاستخدام: ./update.sh
# ==============================================================================

set -e

echo "======================================================"
echo "   🔄 جاري سحب آخر التحديثات من GitHub..."
echo "======================================================"

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$APP_DIR"

# 1. سحب التحديثات من مستودع Git
git pull origin main || git pull

# 2. تفعيل البيئة وتحديث أي مكتبات جديدة
if [ -d "venv" ]; then
    source venv/bin/activate
    pip install -r requirements.txt --quiet
fi

# 3. إعادة تشغيل خدمات السيرفر والبوت فوراً
echo "🚀 إعادة تشغيل الخدمات لتطبيق التعديلات..."
sudo systemctl restart tahteldoo-web.service
sudo systemctl restart tahteldoo-bot.service

echo ""
echo "======================================================"
echo "   ✅ تم تطبيق التعديلات بنجاح وتشغيل أحدث كود!"
echo "======================================================"
